#!/usr/bin/env python3
"""Build the index of every external link cited in the academy.

Writes:
* references/external-links.md — every unique external URL, grouped by the
  section that cites it, with the files that cite it
* the "Appendix A" block in SOURCES.md (between SOURCE-INDEX markers) — a
  summary by domain and by section, plus any links to domains that are not
  on the academy's list of primary sources

Usage: python3 scripts/build-source-index.py [--check]
Standard library only. With --check, exits 1 if a non-primary domain is cited.
"""
from __future__ import annotations

import os
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {"node_modules", ".terraform", "cdk.out", ".git", ".venv", "__pycache__", ".validation", "rendered"}
SKIP_FILES = {"external-links.md"}
URL_RE = re.compile(r"https?://[^\s<>\"'`)\]]+")

# Domains the conventions accept as primary sources.
PRIMARY = (
    "docs.aws.amazon.com", "aws.amazon.com", "builder.aws.com", "repost.aws", "console.aws.amazon.com",
    "github.com", "raw.githubusercontent.com",
    "developer.hashicorp.com", "registry.terraform.io", "www.hashicorp.com", "releases.hashicorp.com",
    "opentofu.org", "www.pulumi.com",
    "arxiv.org",
    "modelcontextprotocol.io", "a2a-protocol.org", "opentelemetry.io", "www.cedarpolicy.com", "docs.cedarpolicy.com",
    "www.checkov.io", "trivy.dev", "aquasecurity.github.io", "www.openpolicyagent.org", "www.conftest.dev",
    "www.infracost.io", "terratest.gruntwork.io", "mermaid.js.org", "plantuml.com", "www.drawio.com",
    "docs.github.com", "www.rfc-editor.org", "datatracker.ietf.org", "semver.org", "spec.openapis.org",
    "registry.npmjs.org", "www.npmjs.com", "pypi.org", "pkg.go.dev", "proxy.golang.org", "repo1.maven.org",
    "nodejs.org", "www.python.org", "docs.python.org", "boto3.amazonaws.com", "www.typescriptlang.org", "jestjs.io",
    "owasp.org", "genai.owasp.org", "www.nist.gov", "csrc.nist.gov", "atlas.mitre.org",
    "www.microsoft.com",  # one corroborating security write-up, see SOURCES.md S-OPS-03
    "strandsagents.com", "www.terraform.io",
)
# Placeholder and example hosts that appear in code samples, not citations.
IGNORE_SUFFIXES = (
    "example.com", "example.org", "example.net", ".amazonaws.com", ".api.aws", "localhost", ".local",
    ".on.aws", ".awsapps.com", ".cloudfront.net", ".internal",
)
IGNORE_HOSTS = {"127.0.0.1", "0.0.0.0", "token.actions.githubusercontent.com", "json-schema.org", "www.w3.org", "schemas.xmlsoap.org"}


def is_ignored(host: str) -> bool:
    if host in IGNORE_HOSTS or not host or "{" in host or "$" in host or "<" in host:
        return True
    return any(host == s or host.endswith(s) for s in IGNORE_SUFFIXES)


def is_primary(host: str) -> bool:
    return any(host == d or host.endswith("." + d) for d in PRIMARY)


def main() -> int:
    check = "--check" in sys.argv
    by_section: dict[str, dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))
    by_domain: dict[str, int] = defaultdict(int)
    non_primary: dict[str, set[str]] = defaultdict(set)
    seen: set[str] = set()

    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            if not name.endswith(".md") or name in SKIP_FILES:
                continue
            path = Path(dirpath) / name
            rel = path.relative_to(ROOT).as_posix()
            section = rel.split("/")[0] if "/" in rel else "(root documents)"
            text = path.read_text(encoding="utf-8")
            if name == "SOURCES.md":
                text = re.sub(r"<!-- SOURCE-INDEX:START.*?<!-- SOURCE-INDEX:END -->", "", text, flags=re.DOTALL)
            for raw in URL_RE.findall(text):
                url = raw.rstrip(".,;:!?*_|\\")
                host = (urlparse(url).hostname or "").lower()
                if is_ignored(host):
                    continue
                by_section[section][url].add(rel)
                if url not in seen:
                    seen.add(url)
                    by_domain[host] += 1
                if not is_primary(host):
                    non_primary[url].add(rel)

    # ---- references/external-links.md
    out = [
        "# External links cited in the academy",
        "",
        "> Generated by `scripts/build-source-index.py`; do not edit by hand.",
        "",
        "Every unique external URL, grouped by the section that cites it. Links are **not fetched** "
        "by this script — it records what is cited so that it can be re-verified.",
        "",
        "[Academy home](../README.md) · [Source register](../SOURCES.md) · [Feature verification matrix](../FEATURE-VERIFICATION.md)",
        "",
        f"**Unique URLs:** {len(seen)} · **Domains:** {len(by_domain)}",
        "",
    ]
    for section in sorted(by_section):
        urls = by_section[section]
        out += [f"## {section}", "", f"{len(urls)} unique links.", "", "| URL | Cited in |", "|:--|:--|"]
        for url in sorted(urls):
            files = sorted(urls[url])
            shown = ", ".join(f"`{f}`" for f in files[:3]) + (f" and {len(files) - 3} more" if len(files) > 3 else "")
            out.append(f"| <{url}> | {shown} |")
        out.append("")
    ref = ROOT / "references" / "external-links.md"
    ref.write_text("\n".join(out), encoding="utf-8")

    # ---- SOURCES.md appendix
    body = [
        "## Appendix A — every external link, by section",
        "",
        f"Generated from the chapters themselves: **{len(seen)} unique external links** across "
        f"**{len(by_domain)} domains**. The full list, with the files that cite each link, is in "
        "[`references/external-links.md`](references/external-links.md).",
        "",
        "### Links by domain",
        "",
        "| Domain | Unique links | Primary source |",
        "|:--|--:|:-:|",
    ]
    for host, count in sorted(by_domain.items(), key=lambda kv: (-kv[1], kv[0])):
        body.append(f"| `{host}` | {count} | {'✅' if is_primary(host) else '⚠️ review'} |")
    body += ["", "### Links by section", "", "| Section | Unique links |", "|:--|--:|"]
    for section in sorted(by_section):
        body.append(f"| `{section}` | {len(by_section[section])} |")
    body.append("")
    if non_primary:
        body += [
            "### Links outside the primary-source list",
            "",
            "These need review against the [authority order](#1-authority-order):",
            "",
            "| URL | Cited in |",
            "|:--|:--|",
        ]
        for url in sorted(non_primary):
            body.append(f"| <{url}> | {', '.join(f'`{f}`' for f in sorted(non_primary[url])[:3])} |")
    else:
        body.append("Every cited domain is on the academy's primary-source list.")

    sources = ROOT / "SOURCES.md"
    text = sources.read_text(encoding="utf-8")
    start = "<!-- SOURCE-INDEX:START — generated by scripts/build-source-index.py; do not edit by hand -->"
    block = f"{start}\n" + "\n".join(body).rstrip() + "\n<!-- SOURCE-INDEX:END -->"
    text = re.sub(r"<!-- SOURCE-INDEX:START.*?<!-- SOURCE-INDEX:END -->", lambda _m: block, text, flags=re.DOTALL)
    sources.write_text(text, encoding="utf-8")

    print(f"Unique external URLs : {len(seen)}")
    print(f"Domains              : {len(by_domain)}")
    print(f"Non-primary URLs     : {len(non_primary)}")
    for url in sorted(non_primary):
        print(f"  REVIEW {url}  <- {sorted(non_primary[url])[0]}")
    return 1 if (check and non_primary) else 0


if __name__ == "__main__":
    sys.exit(main())
