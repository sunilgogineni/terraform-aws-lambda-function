#!/usr/bin/env python3
"""Generate navigation from scripts/content-map.json.

Writes or refreshes, between HTML comment markers so hand-written text is
never touched:

* a previous / up / next footer in every chapter that exists
  (`<!-- NAV:START -->` ... `<!-- NAV:END -->`)
* the chapter table in each section and group README.md
  (`<!-- TOC:START -->` ... `<!-- TOC:END -->`; the README is created if missing)
* the full curriculum in the root README.md (`<!-- CURRICULUM:START -->`)
* CONTENT-MAP.md (whole file) and diagrams/diagram-index.md
  (`<!-- DIAGRAM-INDEX:START -->`)
* the coverage table in PROGRESS.md (`<!-- COVERAGE:START -->`)

Usage:  python3 scripts/build-nav.py [--check] [--skip-footers]
        --check         exits 1 if any file would change (for CI).
        --skip-footers  do not touch chapter files (use while chapters are being written).
Standard library only.
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CMAP = json.loads((ROOT / "scripts" / "content-map.json").read_text(encoding="utf-8"))
CHECK = "--check" in sys.argv
SKIP_FOOTERS = "--skip-footers" in sys.argv
changed: list[str] = []

H1_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)


def rel(from_file: Path, to: Path) -> str:
    return Path(os.path.relpath(to, start=from_file.parent)).as_posix()


def title_of(path: Path, fallback: str) -> str:
    if path.exists():
        m = H1_RE.search(path.read_text(encoding="utf-8"))
        if m:
            return re.sub(r"[`*_]", "", m.group(1)).strip()
    return fallback


def write(path: Path, text: str) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return
    changed.append(str(path.relative_to(ROOT)))
    if not CHECK:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def replace_block(text: str, name: str, body: str, append: bool = True) -> str:
    start = f"<!-- {name}:START — generated by scripts/build-nav.py; do not edit by hand -->"
    end = f"<!-- {name}:END -->"
    block = f"{start}\n{body.rstrip()}\n{end}"
    pattern = re.compile(rf"<!-- {name}:START[^>]*-->.*?<!-- {name}:END -->", re.DOTALL)
    if pattern.search(text):
        return pattern.sub(lambda _m: block, text)
    if not append:
        return text
    return text.rstrip("\n") + "\n\n" + block + "\n"


def md_cell(text: str) -> str:
    return text.replace("|", "\\|")


# ---------------------------------------------------------------- gather
chapters: list[dict] = []  # linear course order
sections: list[dict] = []
for section in CMAP["sections"]:
    sdir = ROOT / section["path"]
    sec = {"dir": sdir, "title": section["title"], "level": section.get("level", ""), "groups": []}
    for group in section["groups"]:
        gdir = sdir / group["path"] if group["path"] else sdir
        grp = {"dir": gdir, "title": group["title"], "chapters": [], "path": group["path"]}
        for fname, title in group["chapters"]:
            ch = {"path": gdir / fname, "title": title, "section": sec, "group": grp}
            grp["chapters"].append(ch)
            chapters.append(ch)
        sec["groups"].append(grp)
    sections.append(sec)

existing = [c for c in chapters if c["path"].exists()]
home = ROOT / "README.md"


def status(ch: dict) -> str:
    return "✅" if ch["path"].exists() else "🚧 planned"


# ---------------------------------------------------------------- chapter footers
for i, ch in enumerate([] if SKIP_FOOTERS else existing):
    path = ch["path"]
    prev_ch = existing[i - 1] if i > 0 else None
    next_ch = existing[i + 1] if i + 1 < len(existing) else None
    sec_readme = ch["section"]["dir"] / "README.md"
    up = f"[{md_cell(ch['section']['title'])}]({rel(path, sec_readme)}) · [Academy home]({rel(path, home)})"
    prev_cell = f"[← {md_cell(title_of(prev_ch['path'], prev_ch['title']))}]({rel(path, prev_ch['path'])})" if prev_ch else " "
    next_cell = f"[{md_cell(title_of(next_ch['path'], next_ch['title']))} →]({rel(path, next_ch['path'])})" if next_ch else " "
    body = "\n---\n\n| Previous | Up | Next |\n|:--|:-:|--:|\n" + f"| {prev_cell} | {up} | {next_cell} |\n"
    write(path, replace_block(path.read_text(encoding="utf-8"), "NAV", body))

# ---------------------------------------------------------------- section / group READMEs
for sec in sections:
    sec_readme = sec["dir"] / "README.md"
    rows = ["| # | Chapter | Group | Status |", "|--:|:--|:--|:-:|"]
    n = 0
    for grp in sec["groups"]:
        for ch in grp["chapters"]:
            n += 1
            link = f"[{md_cell(title_of(ch['path'], ch['title']))}]({rel(sec_readme, ch['path'])})"
            rows.append(f"| {n} | {link} | {md_cell(grp['title'])} | {status(ch)} |")
    body = "\n".join(rows)
    if sec_readme.exists():
        text = sec_readme.read_text(encoding="utf-8")
    else:
        text = f"# {sec['title']}\n\n> **Level:** {sec['level']}\n\n## Chapters\n"
    # A group whose only chapter is its README (patterns, projects) shares the file with nothing else.
    if not any(ch["path"] == sec_readme for grp in sec["groups"] for ch in grp["chapters"]):
        write(sec_readme, replace_block(text, "TOC", body))
    for grp in sec["groups"]:
        if not grp["path"]:
            continue
        g_readme = grp["dir"] / "README.md"
        if any(ch["path"] == g_readme for ch in grp["chapters"]):
            continue
        rows = ["| # | Chapter | Status |", "|--:|:--|:-:|"]
        for k, ch in enumerate(grp["chapters"], start=1):
            link = f"[{md_cell(title_of(ch['path'], ch['title']))}]({rel(g_readme, ch['path'])})"
            rows.append(f"| {k} | {link} | {status(ch)} |")
        if g_readme.exists():
            gtext = g_readme.read_text(encoding="utf-8")
        else:
            gtext = (
                f"# {grp['title']}\n\n"
                f"Part of [{sec['title']}]({rel(g_readme, sec_readme)}) · [Academy home]({rel(g_readme, home)})\n\n"
                "## Chapters\n"
            )
        write(g_readme, replace_block(gtext, "TOC", "\n".join(rows)))

# ---------------------------------------------------------------- curriculum blocks
def curriculum(from_file: Path) -> str:
    out: list[str] = []
    for sec in sections:
        total = sum(len(g["chapters"]) for g in sec["groups"])
        done = sum(1 for g in sec["groups"] for c in g["chapters"] if c["path"].exists())
        sec_readme = sec["dir"] / "README.md"
        out.append(f"\n### [{sec['title']}]({rel(from_file, sec_readme)})\n")
        out.append(f"_Level: {sec['level']} · {done}/{total} chapters written_\n")
        out.append("| Group | Chapters |")
        out.append("|:--|:--|")
        for grp in sec["groups"]:
            links = []
            for ch in grp["chapters"]:
                t = md_cell(title_of(ch["path"], ch["title"]))
                links.append(f"[{t}]({rel(from_file, ch['path'])})" if ch["path"].exists() else f"{t} _(planned)_")
            out.append(f"| **{md_cell(grp['title'])}** | " + "<br/>".join(links) + " |")
    return "\n".join(out)


if home.exists():
    write(home, replace_block(home.read_text(encoding="utf-8"), "CURRICULUM", curriculum(home), append=False))

cmap_md = ROOT / "CONTENT-MAP.md"
total = len(chapters)
done = len(existing)
cmap_text = (
    "# Content map\n\n"
    "Every chapter in the academy, in course order. Generated by `scripts/build-nav.py` from "
    "`scripts/content-map.json` — edit the JSON, not this file.\n\n"
    f"**Chapters written:** {done} of {total} · **Feature verification date:** {CMAP['verified']}\n\n"
    "[Academy home](README.md) · [Learning roadmap](LEARNING-ROADMAP.md) · [Diagram index](diagrams/diagram-index.md)\n"
    + curriculum(cmap_md)
    + "\n"
)
write(cmap_md, cmap_text)

# ---------------------------------------------------------------- diagram index
dindex = ROOT / "diagrams" / "diagram-index.md"
rows = ["| # | Diagram set | Mermaid source | Status |", "|--:|:--|:--|:-:|"]
for num, fname, title in CMAP["diagrams"]:
    p = ROOT / "diagrams" / "mermaid" / fname
    link = f"[`mermaid/{fname}`]({rel(dindex, p)})" if p.exists() else f"`mermaid/{fname}`"
    rows.append(f"| {num} | {md_cell(title)} | {link} | {'✅' if p.exists() else '🚧 planned'} |")
if dindex.exists():
    write(dindex, replace_block(dindex.read_text(encoding="utf-8"), "DIAGRAM-INDEX", "\n".join(rows)))

# ---------------------------------------------------------------- progress coverage
progress = ROOT / "PROGRESS.md"
if progress.exists():
    rows = ["| Section | Chapters written | Planned |", "|:--|--:|--:|"]
    for sec in sections:
        t = sum(len(g["chapters"]) for g in sec["groups"])
        d = sum(1 for g in sec["groups"] for c in g["chapters"] if c["path"].exists())
        rows.append(f"| {md_cell(sec['title'])} | {d} | {t} |")
    dd = sum(1 for _n, f, _t in CMAP["diagrams"] if (ROOT / "diagrams" / "mermaid" / f).exists())
    rows.append(f"| Numbered diagram sets | {dd} | {len(CMAP['diagrams'])} |")
    rows.append(f"| **Total chapters** | **{done}** | **{total}** |")
    write(progress, replace_block(progress.read_text(encoding="utf-8"), "COVERAGE", "\n".join(rows), append=False))

print(f"Chapters in map: {total}; written: {done}; files {'that would change' if CHECK else 'updated'}: {len(changed)}")
for c in changed:
    print(f"  {c}")
sys.exit(1 if (CHECK and changed) else 0)
